'use strict';
const { app, BrowserWindow, ipcMain, clipboard, ClipboardItem, globalShortcut, Tray, Menu, nativeImage, screen, session, powerMonitor } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const { pathToFileURL } = require('node:url');
const { History, ClipboardMonitor, validateSettings, MAX_TEXT_BYTES } = require('./history.cjs');
const { Storage } = require('./storage.cjs');
const TEST_MODE = !app.isPackaged && process.env.PUPA_TEST_MODE === '1';
if (TEST_MODE) app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'pupa-test-')));
app.setName('Pupa');
app.setDesktopName('jp.kuro0315.pupa.desktop');
const gotLock = app.requestSingleInstanceLock();
if (!gotLock) app.quit();
let win, tray, timer, history, storage, monitor, settings;
let paused = false, locked = false, suspended = false, quitting = false, shortcutRegistered = false, storageWarning = null;
let shownAt = 0, hideTimer, mockClipboard = null, settingsBusy = false, copying = false;
const htmlPath = path.join(__dirname, '..', 'dist', 'index.html');
const rendererURL = pathToFileURL(htmlPath).href;
const wayland = process.platform === 'linux' && Boolean(process.env.WAYLAND_DISPLAY || process.env.XDG_SESSION_TYPE === 'wayland');
const state = () => ({ entries: history.snapshot(), settings: { ...settings }, paused,
  status: { shortcutRegistered, storageWarning, platform: process.platform, wayland, version: app.getVersion() } });
const publish = () => { if (win && !win.isDestroyed()) win.webContents.send('pupa:changed', state()); refreshTray(); };
function persistHistory() {
  try { if (settings.persistence) storage.saveHistory(history.snapshot()); else storage.eraseHistory(); }
  catch { storageWarning = '履歴の保存・削除ができませんでした。保存先の権限や空き容量を確認してください。'; }
}
function bounds() {
  const { workArea } = screen.getDisplayNearestPoint(screen.getCursorScreenPoint());
  const width = Math.min(780, workArea.width);
  return { x: workArea.x + workArea.width - width, y: workArea.y, width, height: workArea.height };
}
function show() {
  if (!win || win.isDestroyed() || locked || suspended) return;
  clearTimeout(hideTimer); win.setBounds(bounds()); win.show(); win.focus(); shownAt = Date.now();
  win.webContents.send('pupa:shown');
}
function hide() { clearTimeout(hideTimer); if (win && !win.isDestroyed()) win.hide(); }
function toggle() { if (win?.isVisible()) hide(); else show(); }
function registerShortcut(shortcut) {
  try { return globalShortcut.register(shortcut, toggle); } catch { return false; }
}
function setPaused(value) { paused = value; monitor.setPaused(paused || locked || suspended || copying); publish(); }
function refreshTray() {
  if (!tray || tray.isDestroyed()) return;
  tray.setToolTip(paused ? 'Pupa · 履歴を一時停止中' : 'Pupa · ひとつ前の、つづき。');
  tray.setContextMenu(Menu.buildFromTemplate([
    { label: 'カードをひらく', click: show },
    { label: paused ? '履歴の記録を再開' : '履歴の記録を一時停止', click: () => setPaused(!paused) },
    { label: '設定', click: () => { show(); win.webContents.send('pupa:open-settings'); } },
    { type: 'separator' }, { label: 'Pupa を終了', click: () => { quitting = true; app.quit(); } }
  ]));
}
async function readText() {
  if (TEST_MODE) return mockClipboard;
  const items = await clipboard.read();
  // Respect conventional conceal/transient markers where publishers provide them.
  // Not all password managers do. This is not sensitive-data detection.
  if (items.some(item => item.types.some(type => /concealedtype|transienttype|autogeneratedtype/i.test(type)))) return null;
  for (const item of items) {
    if (!item.types.includes('text/plain')) continue;
    const blob = await item.getType('text/plain');
    if (blob.size > MAX_TEXT_BYTES) return null;
    return blob.text();
  }
  return null;
}
function authorize(event) {
  if (!win || event.sender !== win.webContents || event.senderFrame !== win.webContents.mainFrame || event.senderFrame.url !== rendererURL) throw new Error('この操作は許可されていません。');
}
function handle(channel, action) {
  ipcMain.handle(channel, async (event, value) => {
    authorize(event);
    try { return await action(value); }
    catch (error) { return { ok: false, error: error.message || '操作できませんでした。もう一度お試しください。' }; }
  });
}
function requireEntry(id) {
  if (typeof id !== 'string' || id.length > 100 || !history.get(id)) throw new Error('このカードは見つかりませんでした。');
  return history.get(id);
}
function setupIPC() {
  handle('pupa:state', () => state());
  handle('pupa:copy', async id => {
    const entry = requireEntry(id); const text = entry.text;
    if (copying) throw new Error('コピーしています。少し待ってお試しください。');
    copying = true;
    // Suspend reads for the entire asynchronous write, not only its completion.
    // Otherwise a poll could resurrect the previous (possibly deleted) clipboard.
    monitor.setPaused(true);
    let copied = false;
    try {
      if (TEST_MODE) mockClipboard = text;
      else await clipboard.write([new ClipboardItem({ 'text/plain': text })]);
      copied = true;
    } catch { throw new Error('コピーできませんでした。クリップボードへのアクセスを確認してください。'); }
    finally {
      copying = false;
      monitor.setPaused(paused || locked || suspended);
      if (copied) monitor.noteCopied(text);
    }
    if (settings.hideAfterCopy) hide();
    return { ok: true };
  });
  handle('pupa:delete', id => { requireEntry(id); history.remove(id); persistHistory(); publish(); return { ok: true }; });
  handle('pupa:pin', id => { requireEntry(id); history.pin(id); persistHistory(); publish(); return { ok: true }; });
  handle('pupa:clear', () => { history.clear(); monitor.resetBaseline(); persistHistory(); publish(); return { ok: true }; });
  handle('pupa:pause', value => { if (typeof value !== 'boolean') throw new Error('操作の形式が正しくありません。'); setPaused(value); return { ok: true }; });
  handle('pupa:settings', async patch => {
    if (settingsBusy) return { ok: false, error: '設定を保存しています。少し待ってお試しください。' };
    settingsBusy = true;
    const previous = settings;
    let registeredNew = false;
    try {
      const next = validateSettings(patch, settings);
      const changed = next.shortcut !== previous.shortcut;
      if (changed) {
        registeredNew = registerShortcut(next.shortcut);
        if (!registeredNew) throw new Error('このショートカットは登録できません。他のアプリとの重複や OS の設定を確認してください。');
      }
      if (next.persistence && !previous.persistence) storage.saveHistory(history.snapshot());
      try { storage.saveSettings(next); }
      catch (error) {
        if (next.persistence && !previous.persistence) {
          try { storage.eraseHistory(); }
          catch { storageWarning = '設定の保存に失敗し、平文の履歴ファイルも削除できませんでした。保存をオフにしていても履歴ファイルが残っています。'; publish(); }
        }
        throw error;
      }
      if (changed) { globalShortcut.unregister(previous.shortcut); shortcutRegistered = true; }
      settings = next; history.limit = next.historyLimit; history.trim();
      storageWarning = null; persistHistory(); publish();
      return { ok: true };
    } catch (error) {
      if (registeredNew) { try { globalShortcut.unregister(patch.shortcut); } catch {} }
      return { ok: false, error: error.code ? '設定を保存できませんでした。保存先の権限や空き容量を確認してください。' : error.message };
    } finally { settingsBusy = false; }
  });
  handle('pupa:hide', () => { hide(); return { ok: true }; });
  handle('pupa:quit', () => { quitting = true; app.quit(); return { ok: true }; });
}
async function boot() {
  storage = new Storage(app.getPath('userData'));
  const firstRun = !fs.existsSync(storage.settingsPath);
  const loaded = storage.load(); settings = loaded.settings; storageWarning = loaded.warning;
  history = new History(settings.historyLimit); history.restore(loaded.entries);
  try { storage.saveSettings(settings); } catch { storageWarning = '設定を保存できませんでした。この起動中はメモリだけで動作します。'; }
  const localSession = session.fromPartition('pupa-local', { cache: false });
  localSession.setPermissionRequestHandler((_contents, _permission, callback) => callback(false));
  localSession.setPermissionCheckHandler(() => false);
  localSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*', 'ws://*/*', 'wss://*/*'] }, (_details, callback) => callback({ cancel: true }));
  win = new BrowserWindow({ ...bounds(), show: false, frame: false, transparent: true, backgroundColor: '#00000000',
    resizable: false, maximizable: false, minimizable: false, fullscreenable: false, hasShadow: false,
    alwaysOnTop: true, skipTaskbar: process.platform !== 'linux', title: 'Pupa',
    icon: path.join(__dirname, '..', 'assets', 'icon.png'),
    webPreferences: { preload: path.join(__dirname, 'preload.cjs'), contextIsolation: true, sandbox: true,
      nodeIntegration: false, webSecurity: true, webviewTag: false, spellcheck: false, devTools: !app.isPackaged, session: localSession }
  });
  win.removeMenu();
  win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }));
  win.webContents.on('will-navigate', event => event.preventDefault());
  win.webContents.on('will-attach-webview', event => event.preventDefault());
  win.on('close', event => { if (!quitting) { event.preventDefault(); hide(); } });
  win.on('blur', () => { clearTimeout(hideTimer); hideTimer = setTimeout(() => { if (win && !win.isDestroyed() && !win.isFocused()) hide(); }, Math.max(0, 300 - (Date.now() - shownAt))); });
  win.on('focus', () => clearTimeout(hideTimer));
  try {
    let trayIcon = nativeImage.createFromPath(path.join(__dirname, '..', 'assets', process.platform === 'darwin' ? 'trayTemplate.png' : 'tray.png'));
    if (process.platform === 'darwin') trayIcon.setTemplateImage(true);
    tray = new Tray(trayIcon); tray.on('click', toggle); refreshTray();
  } catch { storageWarning = 'トレイアイコンを表示できません。ショートカット、または Pupa の再起動でカードをひらけます。'; }
  setupIPC();
  monitor = new ClipboardMonitor({ read: readText, onText: text => { history.add(text); persistHistory(); publish(); }, onError: () => {
    if (!storageWarning) { storageWarning = 'クリップボードを読み取れません。OS の権限や Linux のセッションを確認してください。'; publish(); }
  } });
  shortcutRegistered = registerShortcut(settings.shortcut);
  powerMonitor.on('lock-screen', () => { locked = true; monitor.setPaused(true); hide(); });
  powerMonitor.on('unlock-screen', () => { locked = false; monitor.setPaused(paused || suspended || copying); });
  powerMonitor.on('suspend', () => { suspended = true; monitor.setPaused(true); hide(); });
  powerMonitor.on('resume', () => { suspended = false; monitor.setPaused(paused || locked || copying); });
  screen.on('display-removed', () => { if (win.isVisible()) win.setBounds(bounds()); });
  screen.on('display-metrics-changed', () => { if (win.isVisible()) win.setBounds(bounds()); });
  await win.loadFile(htmlPath);
  await monitor.tick(); // Baseline only: never collect what was already copied at launch.
  timer = setInterval(() => monitor.tick(), 700);
  if (firstRun || !tray || !shortcutRegistered || TEST_MODE) show();
  if (TEST_MODE) global.pupaTest = { state, show, hide, toggle, setPaused, tick: () => monitor.tick(),
    setClipboard: text => { mockClipboard = text; }, getClipboard: () => mockClipboard,
    add: text => { history.add(text); publish(); }, isVisible: () => win.isVisible(),
    userData: app.getPath('userData'), getBounds: () => win.getBounds() };
}
if (gotLock) {
  app.whenReady().then(boot).catch(() => { console.error('Pupa could not start. Reinstall the app or inspect local file permissions.'); app.quit(); });
  app.on('second-instance', () => { if (win) show(); });
  app.on('activate', () => { if (win) show(); });
}
app.on('window-all-closed', () => {});
app.on('before-quit', () => { quitting = true; clearInterval(timer); clearTimeout(hideTimer); if (monitor) monitor.setPaused(true); });
app.on('will-quit', () => { globalShortcut.unregisterAll(); if (tray && !tray.isDestroyed()) tray.destroy(); });
