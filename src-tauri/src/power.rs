#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn ordinary_poll_gaps_do_not_reset() {
        assert!(!gap_requires_reset(
            Some(Duration::from_millis(700)),
            Some(Duration::from_millis(700))
        ));
        assert!(!gap_requires_reset(Some(GAP_LIMIT), Some(GAP_LIMIT)));
    }
    #[test]
    fn sleep_or_clock_discontinuity_resets_before_read() {
        let normal = Some(Duration::from_millis(700));
        let gap = Some(Duration::from_secs(60));
        for (monotonic, wall) in [(gap, normal), (normal, gap), (None, normal), (normal, None)] {
            assert!(gap_requires_reset(monotonic, wall));
        }
        let mut guard = PollGapGuard::default();
        let next_monotonic = guard.monotonic + Duration::from_secs(10);
        let next_wall = guard.wall + Duration::from_secs(10);
        assert!(guard.check_at(next_monotonic, next_wall));
        assert!(!guard.check_at(
            next_monotonic + Duration::from_millis(700),
            next_wall + Duration::from_millis(700)
        ));
    }
    #[test]
    fn cooperative_type_markers_are_case_insensitive_and_not_a_text_filter() {
        for marker in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "x-CONCEALEDtype",
        ] {
            assert!(marker_is_sensitive(marker));
        }
        for ordinary in [
            "public.utf8-plain-text",
            "text/plain",
            "public.png",
            "password",
        ] {
            assert!(!marker_is_sensitive(ordinary));
        }
    }
}
